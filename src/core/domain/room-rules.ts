/**
 * ความจุสูงสุดที่ยอมให้กรอก
 *
 * ไม่ได้ตั้งไว้เพราะกลัวเลขใหญ่ล้น แต่เพราะเลขที่หลุดมาผิดปกติ (พิมพ์ศูนย์เกิน วางค่าผิดช่อง)
 * จะไปโผล่เป็น "รองรับ 80000 คน" ในทุกหน้าที่แสดงห้อง โดยไม่มีอะไรทักท้วง
 */
export const MAX_ROOM_CAPACITY = 500;

/** คืนข้อความปัญหา หรือ `null` ถ้าความจุใช้ได้ */
export function capacityProblem(capacity: number): string | null {
  if (!Number.isFinite(capacity) || !Number.isInteger(capacity)) {
    return "ความจุต้องเป็นจำนวนเต็ม";
  }
  if (capacity <= 0) {
    return "ความจุต้องมากกว่า 0";
  }
  if (capacity > MAX_ROOM_CAPACITY) {
    return `ความจุต้องไม่เกิน ${MAX_ROOM_CAPACITY} คน`;
  }
  return null;
}
